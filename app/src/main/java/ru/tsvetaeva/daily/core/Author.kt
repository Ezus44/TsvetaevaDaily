package ru.tsvetaeva.daily.core

/**
 * Поэт, чьи стихи собираются с Викитеки. Названия страниц со стихами на ru.wikisource.org
 * содержат фамилию автора в скобках: «Пророк (Пушкин)», «Облако в штанах (Маяковский)».
 */
enum class Author(
    /** Ключ для настроек и имени файла базы. */
    val key: String,
    /** Фамилия, как она стоит в названиях страниц Викитеки и на вкладке. */
    val tag: String,
    val fullName: String,
    /** «все стихи Цветаевой». */
    val genitive: String,
    /** Начало фамилии — чтобы убрать «(…Цветаева…)», «(…Цветаевой…)» из заголовков. */
    val stem: String,
    /** Годы, в которые автор писал: всё остальное — не год написания (номер страницы, год издания…). */
    val years: IntRange,
    val seedPages: List<String>,
    val seedCategories: List<String>,
    /** Страницы однофамильцев, которые иначе приняли бы за страницы этого автора. */
    private val foreign: Regex? = null,
) {
    TSVETAEVA(
        key = "tsvetaeva", tag = "Цветаева", fullName = "Марина Цветаева", genitive = "Цветаевой", stem = "Цветаев",
        years = Dates.DEFAULT_YEARS,
        seedPages = listOf(
            "Стихотворения 1906—1920 (Цветаева)",
            "Стихотворения 1921—1941 (Цветаева)",
            "Марина Ивановна Цветаева",
            "Автор:Марина Ивановна Цветаева",
        ),
        seedCategories = listOf(
            "Категория:Марина Ивановна Цветаева",
            "Категория:Поэзия Марины Ивановны Цветаевой",
            "Категория:Стихотворения Марины Ивановны Цветаевой",
        ),
    ),
    PARNOK(
        key = "parnok", tag = "Парнок", fullName = "София Парнок", genitive = "Парнок", stem = "Парнок",
        years = 1900..1933,
        seedPages = listOf("Автор:София Яковлевна Парнок"),
        // Сборники (тексты из az.lib.ru) лежат в первой категории, отдельные стихи — во второй.
        seedCategories = listOf(
            "Категория:София Яковлевна Парнок",
            "Категория:Поэзия Софии Яковлевны Парнок",
        ),
    ),
    PUSHKIN(
        key = "pushkin", tag = "Пушкин", fullName = "Александр Пушкин", genitive = "Пушкина", stem = "Пушкин",
        years = 1809..1837,
        // Оглавления по годам — с датами; в названии нет «(Пушкин)», поэтому указаны явно.
        seedPages = listOf(
            "Стихотворения Пушкина 1809—1825",
            "Стихотворения Пушкина 1826—1836",
            "Автор:Александр Сергеевич Пушкин",
        ),
        seedCategories = listOf("Категория:Поэзия Александра Сергеевича Пушкина"),
        // Дядя поэта, Василий Львович Пушкин.
        foreign = Regex("""В\.\s*Л\.\s*Пушкин|Пушкин,?\s+В\.\s*Л\.|Василий\s+Пушкин|Пушкин\s+Василий"""),
    ),
    MAYAKOVSKY(
        key = "mayakovsky", tag = "Маяковский", fullName = "Владимир Маяковский", genitive = "Маяковского",
        stem = "Маяковск", years = 1909..1930,
        seedPages = listOf(
            "Стихотворения Маяковского",
            "Автор:Владимир Владимирович Маяковский",
        ),
        seedCategories = listOf("Категория:Поэзия Владимира Владимировича Маяковского"),
    );

    /** Страница принадлежит автору: «Название (Пушкин)», «Цикл (Пушкин)/3», «X (Пушкин, 1826)». */
    fun isRelevantTitle(title: String): Boolean =
        (title.contains("($tag") || title.contains("$tag)")) && foreign?.containsMatchIn(title) != true

    companion object {
        fun byKey(key: String?): Author? = entries.firstOrNull { it.key == key }
    }
}
